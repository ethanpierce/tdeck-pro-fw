#!/usr/bin/env python3
"""Generate bounded wire fixtures from the pinned OFFICIAL Meshtastic schemas.

Developer-only: .venv/bin/python tools/generate_mesh_fixtures.py --reference PATH
PATH is the protobuf repository root at the commit below. Requires grpcio-tools
and cryptography in the project virtual environment. No firmware dependency.
"""
import argparse
import hashlib
import importlib
from pathlib import Path
import struct
import sys
import tempfile
from functools import reduce
from grpc_tools import protoc
from cryptography.hazmat.primitives.ciphers import Cipher, algorithms, modes

FIRMWARE = "54e0d8d0ab2ff56b3a9ce967e53f79e49af560fb"
PROTOBUFS = "6b1ded439633cd03d4af85b44231b91d1d106278"
ROOT = Path(__file__).resolve().parents[1]


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--reference", required=True, type=Path)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    reference = args.reference.resolve()
    with tempfile.TemporaryDirectory(prefix="tdeck-mesh-proto-") as generated:
        schemas = sorted(str(x) for x in (reference / "meshtastic").glob("*.proto"))
        if not schemas or protoc.main(["protoc", f"-I{reference}", f"--python_out={generated}"] + schemas):
            raise SystemExit("Official protobuf compilation failed")
        sys.path.insert(0, generated)
        mesh = importlib.import_module("meshtastic.mesh_pb2")
        default_key = bytes.fromhex("d4f1bb3a20290759f0bcffabcf4e6901")
        key256 = bytes(range(32))
        nonce = struct.pack("<QI", 0x55667788, 0x11223344) + bytes(4)
        hello = mesh.Data(portnum=1, payload=b"Hello", bitfield=0).SerializeToString(deterministic=True)
        user = mesh.User(id="!11223344", long_name="Handheld", short_name="HH", hw_model=102,
                         role=1, is_unmessagable=True).SerializeToString(deterministic=True)
        node_info = mesh.Data(portnum=4, payload=user, bitfield=0).SerializeToString(deterministic=True)
        channel_hash = reduce(int.__xor__, b"LongFast" + default_key, 0)
        header = struct.pack("<IIIBBBB", 0xFFFFFFFF, 0x11223344, 0x55667788,
                             3 | (3 << 5), channel_hash, 0, 0x44)
        def crypt(key, value):
            return Cipher(algorithms.AES(key), modes.CTR(nonce)).encryptor().update(value)
        vectors = {"Header": header, "Nonce": nonce, "HelloData": hello, "UserPayload": user,
                   "NodeInfoData": node_info, "HelloCipher128": crypt(default_key, hello),
                   "HelloCipher256": crypt(key256, hello), "HelloFrame128": header + crypt(default_key, hello),
                   "CtrPlain": bytes(range(32)), "CtrCipher256": crypt(key256, bytes(range(32)))}
        # Parse encrypted output after independent decryption with the official
        # generated protobuf implementation, not the firmware's hand codec.
        decoded = mesh.Data.FromString(crypt(default_key, vectors["HelloFrame128"][16:]))
        assert decoded.portnum == 1 and decoded.payload == b"Hello" and decoded.HasField("bitfield")
        assert mesh.User.FromString(mesh.Data.FromString(node_info).payload).hw_model == 102
        text = ("// Generated by tools/generate_mesh_fixtures.py from official schemas.\n"
                f"// Firmware {FIRMWARE}; protobufs {PROTOBUFS}.\n"
                f"// mesh.proto SHA256 {hashlib.sha256((reference/'meshtastic/mesh.proto').read_bytes()).hexdigest()}\n"
                "#pragma once\n#include <cstdint>\nnamespace mesh_fixture {\n")
        for name, value in vectors.items():
            text += f"inline constexpr uint8_t {name}[]={{" + ",".join(f"0x{x:02x}" for x in value) + "};\n"
        text += "}\n"
        output = ROOT / "tests/fixtures/meshtastic_v2_7.h"
        if args.check:
            assert output.read_text() == text, "Pinned official fixture mismatch"
        else:
            output.parent.mkdir(parents=True, exist_ok=True)
            output.write_text(text)
        print(f"Verified {len(vectors)} official-schema/AES-CTR fixtures; no RF transmission")

if __name__ == "__main__":
    main()
